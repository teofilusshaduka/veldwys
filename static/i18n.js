// Render a template like "{n} overdue task(s)" with backend-supplied vars.
function tf(key, vars) {
  let s = t(key);
  for (const [k, v] of Object.entries(vars || {})) s = s.split("{" + k + "}").join(v);
  return s.replace(/\(s\)/g, Number(vars && vars.n) === 1 ? "" : "s");
}
